defmodule FirmowidUI.Components.KsefConnection do
  @moduledoc "Shared presentation of the existing KSeF connection and authentication flows."

  use FirmowidUI, :html

  import FirmowidUI.Components.Button
  import FirmowidUI.Components.Inputs
  import FirmowidUI.Components.Link
  import Phoenix.Component, except: [link: 1]

  alias Phoenix.LiveView.Rendered

  @doc "Renders KSeF connection content; the interface supplies its section or widget shell."
  @spec ksef_connection(map()) :: Rendered.t()
  attr :ksef_credential, :any, required: true
  attr :ksef_auth_method, :atom, required: true
  attr :ksef_auth_status, :atom, required: true
  attr :ksef_failure, :any, default: nil
  attr :uploads, :map, required: true
  attr :download_hook, :string, default: "KsefAuthDownload"
  attr :allow_token?, :boolean, default: true
  attr :allow_fetch?, :boolean, default: false
  attr :fetching?, :boolean, default: false

  def ksef_connection(assigns) do
    ~H"""
    <div class="space-y-4">
      <%= if @ksef_credential do %>
        <div class="flex flex-col gap-2">
          <.detail_row label={gettext("Status")}>
            <%= if @ksef_auth_status == :refreshing do %>
              <span class="inline-flex items-center gap-2">
                <span>{gettext("KSeF certificate is being renewed")}</span>
                <.icon name="hero-arrow-path" class="size-5 text-grey-700 motion-safe:animate-spin" />
              </span>
            <% else %>
              <span class="inline-flex items-center gap-2">
                <span>{gettext("Connected to KSeF")}</span>
                <.icon name="hero-check-circle-solid" class="size-5 text-moss-700" />
              </span>
            <% end %>
          </.detail_row>
          <.detail_row label={gettext("Authorization type")}>
            {case @ksef_credential.auth_type do
              :token -> gettext("Token")
              :certificate -> gettext("Certificate")
              :generated_certificate -> gettext("Certificate generated by Firmowid")
            end}
          </.detail_row>
          <.detail_row label={gettext("Expiry date")}>
            {if @ksef_credential.expires_on,
              do: Calendar.strftime(@ksef_credential.expires_on, "%d.%m.%Y"),
              else: "-"}
          </.detail_row>
          <.detail_row class="mbs-2">
            <div class="flex flex-wrap gap-2">
              <.button
                size="small"
                type="button"
                variant="destructive"
                {%{popovertarget: "confirm_disconnect_ksef"}}
              >
                {gettext("Disconnect")}
              </.button>
              <.button
                :if={@allow_fetch?}
                size="small"
                type="button"
                variant="secondary"
                phx-click="fetch_ksef_invoices"
                disabled={@fetching?}
              >
                {if @fetching?,
                  do: gettext("Fetching invoices"),
                  else: gettext("Fetch invoices from KSeF")}
              </.button>
            </div>
          </.detail_row>
        </div>
      <% else %>
        <.detail_row label={gettext("Status")}>
          <span class="inline-flex items-center gap-2">
            <span>{gettext("Not connected to KSeF")}</span>
            <.icon name="hero-x-circle-solid" class="size-5 text-brick-700" />
          </span>
        </.detail_row>

        <div class="mbs-8 mbe-3 text-grey-800">
          <%= if @allow_token? do %>
            {gettext("Connect KSeF using one of three methods.")}
          <% else %>
            {gettext("Connect KSeF with a trusted profile or certificate.")}
          <% end %>
        </div>

        <div
          class="mbe-4 grid w-full max-w-lg grid-cols-[repeat(auto-fit,minmax(min(100%,9rem),1fr))] gap-2"
          role="tablist"
          aria-label={gettext("KSeF authentication method")}
        >
          <.ksef_auth_tab
            method={:trusted_profile}
            current_method={@ksef_auth_method}
            label={gettext("Trusted Profile")}
            panel_id="ksef-external-signature-flow"
          />
          <.ksef_auth_tab
            method={:certificate}
            current_method={@ksef_auth_method}
            label={gettext("KSeF certificate")}
            panel_id="ksef-certificate-auth-flow"
          />
          <.ksef_auth_tab
            :if={@allow_token?}
            method={:token}
            current_method={@ksef_auth_method}
            label={gettext("Token")}
            panel_id="ksef-token-auth-flow"
          />
        </div>

        <div
          :if={@allow_token? and @ksef_auth_method == :token}
          id="ksef-token-auth-flow"
          role="tabpanel"
          aria-labelledby="ksef-auth-tab-token"
          class="w-full max-w-lg space-y-5"
        >
          <div class="flex gap-3 rounded-lg border border-rust-700 bg-rust-200 p-4 text-sm text-grey-900">
            <.icon
              name="hero-exclamation-triangle-solid"
              class="mbs-0.5 size-5 shrink-0 text-rust-800"
            />
            <div class="text-rust-800">
              <p class="font-semibold">{gettext("Method being phased out")}</p>
              <p class="mbs-1">
                {gettext(
                  "KSeF tokens will be supported only until 1 January 2027. We recommend authenticating with a Trusted Profile or a KSeF certificate."
                )}
              </p>
            </div>
          </div>

          <p class="text-sm text-grey-600">
            {gettext("Follow the steps below to connect Firmowid to KSeF.")}
          </p>

          <ol class="space-y-6">
            <.ksef_step number={1}>
              <:title>{gettext("Generate a token")}</:title>
              <:content>
                <.linked_sentence
                  href="https://ap.ksef.mf.gov.pl/web/"
                  link_label="KSeF"
                  text={
                    gettext(
                      "Go to %{link}, sign in and generate a token with permission to issue and view invoices.",
                      link: "__LINK__"
                    )
                  }
                />
              </:content>
            </.ksef_step>

            <.ksef_step number={2} content_class="mbs-3">
              <:title><label for="ksef_token">{gettext("Paste the token")}</label></:title>
              <:content>
                <form phx-submit="save_ksef_token" id="ksef-token-form" class="space-y-4">
                  <.input
                    type="password"
                    id="ksef_token"
                    name="ksef_token"
                    value=""
                    required
                    input_class="w-full"
                  />
                  <div class="flex justify-end">
                    <.button
                      type="submit"
                      variant="secondary"
                      size="small"
                      phx-disable-with={gettext("Connecting...")}
                    >
                      {gettext("Connect to KSeF")}
                    </.button>
                  </div>
                </form>
                <.ksef_auth_status status={@ksef_auth_status} failure={@ksef_failure} />
              </:content>
            </.ksef_step>
          </ol>
        </div>

        <div
          :if={@ksef_auth_method == :trusted_profile}
          id="ksef-external-signature-flow"
          role="tabpanel"
          aria-labelledby="ksef-auth-tab-trusted_profile"
          class="w-full max-w-lg space-y-5"
        >
          <p class="text-sm text-grey-600">
            {gettext("Follow the steps below to connect Firmowid to KSeF.")}
          </p>
          <ol class="space-y-6">
            <.ksef_step number={1} class="justify-items-start">
              <:title>
                <.button
                  id="download-ksef-auth-token-request"
                  phx-hook={@download_hook}
                  type="button"
                  variant="unstyled"
                  class="cursor-pointer underline focus-visible:outline-2 active:opacity-80"
                  phx-click="download_ksef_auth_token_request"
                >
                  {gettext("Download the request")}
                </.button>
              </:title>
            </.ksef_step>
            <.ksef_step number={2}>
              <:title>{gettext("Sign the file")}</:title>
              <:content>
                <.linked_sentence
                  href="https://podpis.gov.pl/podpisz-dokument-elektronicznie/"
                  link_label={pgettext("KSeF signing link", "Trusted Profile")}
                  text={
                    gettext("Sign the downloaded file with %{link} or a qualified signature.",
                      link: "__LINK__"
                    )
                  }
                />
              </:content>
            </.ksef_step>
            <.ksef_step number={3} content_class="mbs-3">
              <:title>
                <label for={@uploads.signed_auth_token_request.ref}>{gettext("Upload the signed file")}</label>
              </:title>
              <:content>
                <form
                  phx-change="validate_signed_auth_token_request"
                  phx-submit="upload_signed_auth_token_request"
                  id="ksef-signed-auth-token-request-form"
                  class="space-y-4"
                >
                  <.file_upload
                    upload={@uploads.signed_auth_token_request}
                    prompt={gettext("Add the signed file (.xml)")}
                    show_errors={false}
                  />
                  <div :if={@ksef_auth_status in [:idle, :working, :failed]} class="flex justify-end">
                    <.button
                      type="submit"
                      variant="secondary"
                      size="small"
                      phx-disable-with={gettext("Sending...")}
                    >
                      {gettext("Send the file")}
                    </.button>
                  </div>
                </form>
                <.ksef_auth_status status={@ksef_auth_status} failure={@ksef_failure} />
              </:content>
            </.ksef_step>
          </ol>
        </div>

        <div
          :if={@ksef_auth_method == :certificate}
          id="ksef-certificate-auth-flow"
          role="tabpanel"
          aria-labelledby="ksef-auth-tab-certificate"
          class="w-full max-w-lg space-y-5"
        >
          <p class="text-sm text-grey-600">
            {gettext("Follow the steps below to connect Firmowid to KSeF.")}
          </p>
          <ol class="space-y-6">
            <.ksef_step number={1}>
              <:title>{gettext("Generate a KSeF certificate")}</:title>
              <:content>
                <.linked_sentence
                  href="https://ap.ksef.mf.gov.pl/web/"
                  link_label="KSeF"
                  purpose="„Uwierzytelnienie w systemie KSeF”"
                  text={
                    gettext(
                      "Go to %{link}, sign in and generate a certificate with the purpose %{purpose}.",
                      link: "__LINK__",
                      purpose: "__PURPOSE__"
                    )
                  }
                />
              </:content>
            </.ksef_step>
            <.ksef_step number={2}>
              <:title>{gettext("Upload the certificate and private key")}</:title>
              <:content>
                {gettext(
                  "Add the downloaded .crt and .key files, then enter the private key password."
                )}
                <form
                  phx-change="validate_ksef_certificate"
                  phx-submit="save_ksef_certificate"
                  id="ksef-certificate-form"
                  class="mbs-3 space-y-4"
                >
                  <.file_upload
                    upload={@uploads.ksef_credentials}
                    prompt={gettext("Add the certificate and private key")}
                    prompt_class="font-medium"
                  />
                  <label for="private_key_password" class="flex w-full flex-col gap-1">
                    <span class="text-sm/snug text-grey-700">{gettext("Private key password")}</span>
                    <.input
                      type="password"
                      name="private_key_password"
                      id="private_key_password"
                      value=""
                      required
                      input_class="w-full"
                    />
                  </label>
                  <div class="flex justify-end">
                    <.button
                      type="submit"
                      variant="secondary"
                      size="small"
                      phx-disable-with={gettext("Connecting...")}
                    >
                      {gettext("Send the certificate")}
                    </.button>
                  </div>
                </form>
                <.ksef_auth_status status={@ksef_auth_status} failure={@ksef_failure} />
              </:content>
            </.ksef_step>
          </ol>
        </div>
      <% end %>

      <div
        id="confirm_disconnect_ksef"
        popover
        role="alertdialog"
        aria-labelledby="confirm_disconnect_ksef_title"
        class="m-auto w-[min(90vi,32rem)] rounded-lg border border-grey-200 bg-white p-6 shadow-lg"
      >
        <h3 id="confirm_disconnect_ksef_title" class="text-lg font-semibold text-grey-900">
          {gettext("Confirm disconnection")}
        </h3>
        <p class="mbs-3 text-sm text-grey-700">
          {gettext("Disconnecting will stop the current KSeF integration for this organization.")}
        </p>
        <div class="mbs-6 flex flex-wrap justify-end gap-3">
          <.button
            type="button"
            variant="secondary"
            size="small"
            {%{popovertarget: "confirm_disconnect_ksef", popovertargetaction: "hide"}}
          >
            {gettext("Cancel")}
          </.button>
          <.button
            type="button"
            variant="destructive"
            size="small"
            phx-click="disconnect_ksef"
            {%{popovertarget: "confirm_disconnect_ksef", popovertargetaction: "hide"}}
          >
            {gettext("Disconnect")}
          </.button>
        </div>
      </div>
    </div>
    """
  end

  attr :label, :string, default: ""
  attr :class, :string, default: nil
  slot :inner_block, required: true

  defp detail_row(assigns) do
    ~H"""
    <div class={["grid grid-cols-2 items-baseline gap-x-5", @class]}>
      <div class="text-end text-sm/snug text-grey-700">{@label}</div>
      <div class="min-w-0 text-base/snug wrap-break-word text-grey-900">
        {render_slot(@inner_block)}
      </div>
    </div>
    """
  end

  attr :text, :string,
    required: true,
    doc: "Translated sentence with `__LINK__` (and `__PURPOSE__`) markers."

  attr :href, :string, required: true
  attr :link_label, :string, required: true
  attr :purpose, :string, default: nil

  defp linked_sentence(assigns) do
    assigns =
      assign(
        assigns,
        :parts,
        Regex.split(~r/__LINK__|__PURPOSE__/, assigns.text, include_captures: true)
      )

    ~H"""
    <span phx-no-format><%= for part <- @parts do %><%= case part do %><% "__LINK__" -> %><.link
            kind="unstyled"
            external={@href}
            target="_blank"
            rel="noopener noreferrer"
            class="inline-flex items-center gap-1 text-sm text-rust-700 underline underline-offset-4"
          >
            {@link_label}
          </.link><% "__PURPOSE__" -> %><span class="font-medium">{@purpose}</span><% text -> %>{text}<% end %><% end %></span>
    """
  end

  attr :upload, :any, required: true
  attr :prompt, :string, required: true
  attr :prompt_class, :string, default: nil
  attr :show_errors, :boolean, default: true

  defp file_upload(assigns) do
    ~H"""
    <label
      class="flex w-full cursor-pointer justify-center rounded-md border-2 border-dashed border-rust-700 px-6 py-8 focus-within:outline-2 focus-within:outline-rust-700 active:opacity-80"
      phx-drop-target={@upload.ref}
    >
      <div class="text-center text-sm text-rust-700">
        <div :if={Enum.empty?(@upload.entries)} class={@prompt_class}>{@prompt}</div>
        <.live_file_input upload={@upload} class="sr-only" />
        <div :for={entry <- @upload.entries}>
          <p>{entry.client_name}</p>
          <p :for={error <- if(@show_errors, do: upload_errors(@upload, entry), else: [])}>
            {present_upload_error(error)}
          </p>
        </div>
        <p :for={error <- if(@show_errors, do: upload_errors(@upload), else: [])}>
          {present_upload_error(error)}
        </p>
      </div>
    </label>
    """
  end

  attr :number, :integer, required: true
  attr :class, :string, default: nil
  attr :content_class, :string, default: nil
  slot :title, required: true
  slot :content

  defp ksef_step(assigns) do
    ~H"""
    <li class={["grid grid-cols-[min-content_minmax(0,1fr)] items-center gap-x-3", @class]}>
      <span class="flex size-7 shrink-0 items-center justify-center rounded-full bg-rust-700 text-sm font-semibold text-white">{@number}</span>
      <div class="text-sm font-semibold text-grey-900">{render_slot(@title)}</div>
      <div :for={content <- @content} class={["col-start-2 text-sm text-grey-600", @content_class]}>
        {render_slot(content)}
      </div>
    </li>
    """
  end

  attr :method, :atom, required: true
  attr :current_method, :atom, required: true
  attr :label, :string, required: true
  attr :panel_id, :string, required: true

  defp ksef_auth_tab(assigns) do
    ~H"""
    <.button
      id={"ksef-auth-tab-#{@method}"}
      type="button"
      role="tab"
      aria-selected={if(@current_method == @method, do: "true", else: "false")}
      aria-controls={@panel_id}
      variant={if(@current_method == @method, do: "secondary", else: "outline")}
      size="small"
      phx-click="select_ksef_auth_method"
      phx-value-method={@method}
      class="w-full focus-visible:outline-2 focus-visible:outline-rust-700 active:opacity-80"
    >
      {@label}
    </.button>
    """
  end

  attr :status, :atom, required: true
  attr :failure, :any, default: nil

  defp ksef_auth_status(assigns) do
    ~H"""
    <div
      :if={
        @status in [
          :authenticating_epuap,
          :preparing_enrollment,
          :wait_for_certificate,
          :authenticating,
          :failed
        ] || @failure
      }
      role="status"
      class={[
        "mbs-4 flex items-start gap-2 rounded-lg border px-3 py-2.5 text-sm",
        if(@status == :failed,
          do: "border-brick-200 bg-brick-100 text-brick-900",
          else: "border-grey-200 bg-grey-50 text-grey-700"
        )
      ]}
    >
      <.icon
        :if={@status == :failed}
        name="hero-x-circle-solid"
        class="mbs-0.5 size-5 shrink-0 text-brick-700"
      />
      <.icon
        :if={@status != :failed}
        name="hero-arrow-path"
        class="mbs-0.5 size-5 shrink-0 motion-safe:animate-spin"
      />
      <span>{failure_message(@failure) || present_ksef_auth_status(@status)}</span>
    </div>
    """
  end

  defp present_upload_error(:too_large), do: gettext("The file is too large.")
  defp present_upload_error(:too_many_files), do: gettext("Choose exactly two files.")
  defp present_upload_error(:not_accepted), do: gettext("Only .crt and .key files are allowed.")

  defp failure_message(nil), do: nil
  defp failure_message(%{reason: reason}), do: credential_failure_message(reason)

  defp credential_failure_message(:certificate_limit_exhausted),
    do: gettext("The KSeF certificate limit has been reached.")

  defp credential_failure_message(:invalid_credentials) do
    gettext("Could not authenticate with KSeF. Check the certificate, key and password and try again.")
  end

  defp credential_failure_message(:authentication_failed), do: gettext("KSeF authentication failed.")

  defp credential_failure_message(_reason), do: gettext("An error occurred while generating the KSeF certificate.")

  defp present_ksef_auth_status(:authenticating), do: gettext("Authenticating with KSeF.")
  defp present_ksef_auth_status(:authenticating_epuap), do: gettext("Authenticating with KSeF.")

  defp present_ksef_auth_status(:preparing_enrollment), do: gettext("Preparing the certificate request.")

  defp present_ksef_auth_status(:wait_for_certificate), do: gettext("KSeF is issuing the certificate.")

  defp present_ksef_auth_status(:failed), do: gettext("Could not connect to KSeF. Please try again.")
end

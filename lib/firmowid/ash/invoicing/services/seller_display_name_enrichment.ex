defmodule Firmowid.Ash.Invoicing.Services.SellerDisplayNameEnrichment do
  @moduledoc """
  Derives a seller display name for cost invoices from invoice contents, together
  with a short note on what the seller does for the invoice description.

  Historical cost invoices are used only as prompt context. The final display
  name is always generated by the LLM when a seller name is present.

  For a seller the tenant has not named before, the model may look the seller up
  on the web, so that e.g. a franchisee shows as the franchise brand.
  """

  alias Firmowid.Ash.Invoicing.CostInvoice
  alias Firmowid.ErrorKind
  alias OpenaiEx.Responses

  require Ash.Expr
  require Ash.Query
  require Logger

  @candidate_limit 20
  @max_history_scan 100
  @prompt_version 3

  @web_search_tool %{
    type: "web_search",
    search_context_size: "medium",
    user_location: %{type: "approximate", country: "PL"}
  }

  @response_format %{
    type: "json_schema",
    name: "seller",
    strict: true,
    schema: %{
      type: "object",
      properties: %{display_name: %{type: "string"}, seller_activity: %{type: "string"}},
      required: ["display_name", "seller_activity"],
      additionalProperties: false
    }
  }

  @type result :: %{display_name: String.t(), seller_activity: String.t() | nil}

  @type candidate :: %{
          display_name: String.t(),
          seller: String.t() | nil,
          seller_nip: String.t() | nil
        }

  @doc """
  Generates a display name and seller activity, or returns nil without a seller
  or on failure.

  Web search runs only when no other invoice of the tenant from the same seller
  has a display name yet.
  """
  @spec generate_display_name(map(), keyword()) :: result() | nil
  def generate_display_name(document, opts \\ []) do
    seller = normalize_text(document[:seller] || document["seller"])
    seller_nip = normalize_tax_id(document[:seller_nip] || document["seller_nip"])
    seller_address = normalize_text(document[:seller_address] || document["seller_address"])
    items_list = normalize_items_list(document[:items_list] || document["items_list"])
    ash_opts = Keyword.get(opts, :ash_opts, [])
    current_cost_invoice_id = Keyword.get(opts, :current_cost_invoice_id)

    if is_nil(seller) do
      nil
    else
      historical_candidates =
        historical_candidates(seller, seller_nip, current_cost_invoice_id, ash_opts)

      web_search? = not known_seller?(historical_candidates, seller, seller_nip)

      seller
      |> user_prompt(seller_address, seller_nip, items_list, historical_candidates)
      |> generate_via_llm(web_search?)
      |> normalize_result()
    end
  end

  @spec historical_candidates(String.t(), String.t() | nil, Ash.UUID.t() | nil, keyword()) ::
          [candidate()]
  defp historical_candidates(seller, seller_nip, current_cost_invoice_id, ash_opts) do
    current_cost_invoice_id
    |> historical_candidates_query(ash_opts)
    |> Ash.Query.filter(
      Ash.Expr.expr(
        (not is_nil(^seller_nip) and seller_nip == ^seller_nip) or
          contains(seller, ^seller) or
          contains(seller_display_name, ^seller)
      )
    )
    |> Ash.Query.sort(inserted_at: :desc, seller_display_name: :asc, seller: :asc, id: :desc)
    |> Ash.Query.limit(@max_history_scan)
    |> then(&CostInvoice.list!(Keyword.put(ash_opts, :query, &1)))
    |> unique_candidates()
    |> Enum.take(@candidate_limit)
  end

  # A display name equal to the legal name is the fallback after a failed
  # generation, so it does not count as a known seller.
  @spec known_seller?([candidate()], String.t(), String.t() | nil) :: boolean()
  defp known_seller?(candidates, seller, seller_nip) do
    candidates
    |> Enum.reject(&(&1.display_name == &1.seller))
    |> Enum.any?(&same_seller?(&1, seller, seller_nip))
  end

  defp same_seller?(candidate, seller, nil),
    do: candidate.seller && String.downcase(candidate.seller) == String.downcase(seller)

  defp same_seller?(candidate, _seller, seller_nip), do: candidate.seller_nip == seller_nip

  @spec historical_candidates_query(Ash.UUID.t() | nil, keyword()) :: Ash.Query.t()
  defp historical_candidates_query(current_cost_invoice_id, ash_opts) do
    %{}
    |> CostInvoice.query_to_list(ash_opts)
    |> Ash.Query.select([:id, :seller, :seller_display_name, :seller_nip, :inserted_at])
    |> Ash.Query.filter(Ash.Expr.expr(not is_nil(seller_display_name) and seller_display_name != ""))
    |> maybe_exclude_current_invoice(current_cost_invoice_id)
  end

  defp maybe_exclude_current_invoice(query, nil), do: query

  defp maybe_exclude_current_invoice(query, current_cost_invoice_id) do
    Ash.Query.filter(query, Ash.Expr.expr(id != ^current_cost_invoice_id))
  end

  @spec unique_candidates([struct()]) :: [candidate()]
  defp unique_candidates(records) do
    {candidates, _seen} =
      Enum.reduce(records, {[], MapSet.new()}, fn record, {acc, seen} ->
        display_name = normalize_text(record.seller_display_name || record.seller)

        if is_nil(display_name) or MapSet.member?(seen, display_name) do
          {acc, seen}
        else
          candidate = %{
            display_name: display_name,
            seller: normalize_text(record.seller),
            seller_nip: normalize_tax_id(record.seller_nip)
          }

          {[candidate | acc], MapSet.put(seen, display_name)}
        end
      end)

    Enum.reverse(candidates)
  end

  @spec generate_via_llm(String.t(), boolean()) :: map() | nil
  defp generate_via_llm(user_prompt, web_search?) do
    openai =
      :firmowid
      |> Application.get_env(:openai_api_key)
      |> OpenaiEx.new()
      |> OpenaiEx.with_receive_timeout(60_000)
      |> configure_openai_client()

    request = %{
      model: "gpt-6-luna",
      reasoning: %{effort: "none"},
      # Web search calls count towards this limit.
      max_output_tokens: 1000,
      instructions: developer_prompt(),
      input: user_prompt,
      text: %{format: @response_format}
    }

    openai
    |> Responses.create!(maybe_add_web_search(request, web_search?))
    |> Map.fetch!("output")
    |> Enum.filter(&(&1["type"] == "message"))
    |> Enum.flat_map(& &1["content"])
    |> Enum.map_join(&(&1["text"] || ""))
    |> Jason.decode!()
  rescue
    error ->
      Logger.warning("Failed to generate seller display name via OpenAI",
        error_kind: ErrorKind.classify(error)
      )

      nil
  end

  # Left to choose, the model often skips the search and guesses from the name.
  defp maybe_add_web_search(request, true), do: Map.merge(request, %{tools: [@web_search_tool], tool_choice: "required"})

  defp maybe_add_web_search(request, false), do: request

  defp configure_openai_client(openai) do
    case Application.get_env(:firmowid, :openai_ex, [])[:base_url] do
      base_url when is_binary(base_url) and base_url != "" ->
        OpenaiEx.with_base_url(openai, base_url)

      _ ->
        openai
    end
  end

  defp developer_prompt do
    String.trim("""
    Jesteś asystentem księgowym. Tworzysz krótką, czytelną nazwę wyświetlaną sprzedawcy
    dla faktur kosztowych. Użytkownik ma od razu wiedzieć, gdzie zrobił zakup.

    Zwracasz:
    - display_name: jedna nazwa, bez cudzysłowów, linków, źródeł i komentarza.
    - seller_activity: jedno krótkie zdanie, czym zajmuje się sprzedawca i co się u niego
      kupuje (np. "Stacja paliw sieci Orlen prowadzona przez franczyzobiorcę"). Pusty tekst,
      gdy nie wiadomo.

    Zasady:
    - Historyczne nazwy traktuj wyłącznie jako sugestie i kontekst, nie jako obowiązkową odpowiedź.
    - Preferuj nazwy krótsze od pełnej nazwy prawnej, ale nadal jednoznaczne dla człowieka.
    - Usuń zbędne formy prawne, jeśli nie są potrzebne do identyfikacji.
    - Wygeneruj najlepszą krótką nazwę na podstawie bieżącej faktury i kontekstu historycznego.
    - Jeśli masz wyszukiwarkę, sprawdź w internecie, czym jest sprzedawca (np. czy to
      franczyzobiorca sieci). Franczyzę pokaż marką sieci znaną klientowi i miastem.
    - Używaj nazwy marki, pod którą punkt występuje wobec klientów, w pełnej postaci,
      gdy skrót jest niejednoznaczny.
    - Gdy nazwa nic nie mówi klientowi albo firma działa pod kilkoma markami i nie wiadomo,
      pod którą kupowano, dodaj po myślniku krótko, co sprzedaje.
    - Miasto dodaj tylko do lokalnego punktu sieci (sklep, stacja, restauracja), nigdy do
      firmy sprzedającej z centrali, przez internet albo w abonamencie.
    - Nie zgaduj: markę sieci i miasto podaj tylko wtedy, gdy wynikają z danych faktury lub
      ze źródeł o tym konkretnym sprzedawcy (zgodny NIP albo adres), a nie o firmie
      o podobnej nazwie. Inaczej skróć nazwę prawną.
    - Nie dodawaj innych informacji, których nie ma w danych wejściowych ani w źródłach.

    Przykłady:
    - "STACJA PALIW PKN ORLEN NR 7333 ''BILMEX - TANK'' SPÓŁKA Z OGRANICZONĄ
      ODPOWIEDZIALNOŚCIĄ SPÓŁKA KOMANDYTOWA 30-348 KRAKÓW UL.GROTA ROWECKIEGO
      33 BDO00015385" -> "Stacja paliw Orlen w Krakowie"
      - franczyza, z perspektywy klienta to "Orlen", a nie "Bilmex"
      - miasto jest ważną informacją gdy mamy doczynienia z franczyzą
    - "Jan Kowalski Handel", sklep sieci Żabka w Krakowie -> "Żabka, Kraków"
      - osoba fizyczna prowadząca sklep franczyzowy, klient zna tylko markę
    - "NEW PIZZA HOTE NYPD Liteuska 22A" (błędy z odczytu paragonu), pizzeria sieci
      New York Pizza Department w Krakowie -> "New York Pizza Department, Kraków"
      - "NYPD" to skrót marki, pełna nazwa jest jednoznaczna
    - "LANTRE SPÓŁKA Z OGRANICZONĄ ODPOWIEDZIALNOŚCIĄ" -> "Lantre"
      - prosta nazwa, bez zbędnych form prawnych
      - zawsze chcemy mieć słowa pisane wielką literą, nawet jeśli w danych
      wejściowych są małymi / całe wielkimi literami
    - "PGE POLSKA GRUPA ENERGETYCZNA SPÓŁKA AKCYJNA" -> "PGE"
      - akronim zawsze dużymi literami, ale znowu - bez zbędnych form prawnych
    - "INZUZO-NAJEM SP. Z O.O.", Wrocław, wynajem apartamentów na doby pod kilkoma
      markami -> "Inzuzo-Najem – apartamenty, Wrocław"
    - "Apple Polska Sp. z o.o." -> "Apple"
      - znana marka wystarczy, bez kraju i nazwy spółki zależnej
    - "VIKINGCO POLAND SPÓŁKA Z OGRANICZONĄ ODPOWIEDZIALNOŚCIĄ" -> "VikingCo"
    """)
  end

  @spec user_prompt(String.t(), String.t() | nil, String.t() | nil, [map()], [candidate()]) ::
          String.t()
  defp user_prompt(seller, seller_address, seller_nip, items_list, historical_candidates) do
    String.trim("""
    Wersja promptu: #{@prompt_version}

    Dane bieżącej faktury:
    - pełna nazwa sprzedawcy: #{seller}
    - adres sprzedawcy: #{seller_address || "brak"}
    - NIP / tax id: #{seller_nip || "brak"}
    - pozycje faktury: #{inspect(Enum.take(items_list, 5))}

    Historyczne nazwy pasujące częściowo (maks. #{@candidate_limit}):
    #{format_candidates(historical_candidates)}

    Zwróć najlepszą nazwę wyświetlaną sprzedawcy i to, czym się zajmuje.
    """)
  end

  defp format_candidates([]), do: "- brak"

  defp format_candidates(candidates) do
    candidates
    |> Enum.with_index(1)
    |> Enum.map_join("\n", fn {candidate, index} ->
      "- #{index}. display_name=#{candidate.display_name}; seller=#{candidate.seller || "brak"}; seller_nip=#{candidate.seller_nip || "brak"}"
    end)
  end

  @spec normalize_result(map() | nil) :: result() | nil
  defp normalize_result(%{"display_name" => display_name, "seller_activity" => seller_activity}) do
    case display_name |> String.trim() |> String.trim("\"'") do
      "" -> nil
      normalized -> %{display_name: normalized, seller_activity: normalize_text(seller_activity)}
    end
  end

  defp normalize_result(nil), do: nil

  @spec normalize_text(String.t() | nil) :: String.t() | nil
  defp normalize_text(nil), do: nil

  defp normalize_text(value) do
    case value |> to_string() |> String.trim() do
      "" -> nil
      normalized -> normalized
    end
  end

  @spec normalize_tax_id(String.t() | nil) :: String.t() | nil
  defp normalize_tax_id(nil), do: nil

  defp normalize_tax_id(value) do
    value
    |> to_string()
    |> String.replace(~r/[^\p{N}A-Za-z]/u, "")
    |> String.upcase()
    |> case do
      "" -> nil
      normalized -> normalized
    end
  end

  defp normalize_items_list(items_list) when is_list(items_list), do: items_list
  defp normalize_items_list(_), do: []
end

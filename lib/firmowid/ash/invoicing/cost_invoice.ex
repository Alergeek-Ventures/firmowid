    domain: Firmowid.Ash.Invoicing,
    data_layer: AshPostgres.DataLayer,
    authorizers: [Ash.Policy.Authorizer],
    extensions: [AshOban, AshEvents.Events],
    notifiers: [Ash.Notifier.PubSub]

  alias AshMoney.Types.Money, as: MoneyType
  alias AshOban.Checks.AshObanInteraction
  alias Firmowid.Ash.Checks.ActorRole
  alias Firmowid.Ash.Checks.AtLeastRole
  alias Firmowid.Ash.Checks.IsSystemActor
  alias Firmowid.Ash.Checks.SystemActorRole
  alias Firmowid.Ash.Finances
  alias Firmowid.Ash.Invoicing.Changes.ComputeCostInvoiceDescription
  alias Firmowid.Ash.Invoicing.Changes.ComputeCostInvoiceSellerDisplayName
  alias Firmowid.Ash.Invoicing.Changes.EnqueueMissingCostInvoiceDescriptionRefresh
  alias Firmowid.Ash.Invoicing.Changes.EnqueueMissingCostInvoiceSellerDisplayNameRefresh
  alias Firmowid.Ash.Invoicing.Changes.RecordManualMatch
  alias Firmowid.Ash.Invoicing.Changes.RequireTransactionIds
  alias Firmowid.Ash.Invoicing.CostInvoiceTransaction
  alias Firmowid.Ash.Invoicing.InvoiceMatching
  alias Firmowid.Ash.Invoicing.Signals
  alias Firmowid.Ash.Resource

  require Resource

  @correction_invoice_types [:kor, :kor_zal, :kor_roz]

  postgres do
    table "cost_invoices"
    repo Firmowid.Repo

    custom_statements do
      statement :allow_pending_cost_invoice_entity_tags do
        up "DROP TRIGGER cost_invoice_entity_tag_taggable_trigger ON cost_invoice_entity_tags;"

        down """
        CREATE TRIGGER cost_invoice_entity_tag_taggable_trigger
        BEFORE INSERT ON cost_invoice_entity_tags
        FOR EACH ROW EXECUTE FUNCTION check_cost_invoice_entity_tag_taggable();
        """
      end
    end

    check_constraints do
      check_constraint :amount,
                       "cost_invoices_non_correction_amount_non_positive",
                       check: """
                       COALESCE((invoice_type)::text = ANY ((ARRAY['kor'::character varying, 'kor_zal'::character varying, 'kor_roz'::character varying])::text[]), false)
                       OR (amount).amount <= (0)::numeric
                       """,
                       message: "must be <= 0 for non-correction invoices"
    end

    references do
      reference :original_invoice, ignore?: true
    end
  end

  oban do
    use_tenant_from_record? true

    triggers do
      trigger :refresh_missing_description do
        action :refresh_description
        read_action :read_global
        where expr(description == "")
        scheduler_cron "0 * * * *"
        max_attempts 2
        queue :cost_invoices

        worker_module_name Firmowid.Ash.Invoicing.CostInvoice.Worker.RefreshMissingDescription

        scheduler_module_name Firmowid.Ash.Invoicing.CostInvoice.Scheduler.RefreshMissingDescription
      end

      trigger :refresh_missing_seller_display_name do
        action :refresh_seller_display_name
        read_action :read_global
        where expr(is_nil(seller_display_name))
        scheduler_cron false
        # The generator reads earlier invoices of the record's tenant for naming hints.
        default_actor %Firmowid.Ash.SystemActor{org_id: nil, role: :cost_invoice_processor}
        max_attempts 2
        queue :cost_invoices

        worker_module_name Firmowid.Ash.Invoicing.CostInvoice.Worker.RefreshMissingSellerDisplayName

        scheduler_module_name Firmowid.Ash.Invoicing.CostInvoice.Scheduler.RefreshMissingSellerDisplayName
      end
    end
  end

  events do
    event_log Firmowid.Ash.Events.Event
    only_actions [:connect_transactions, :disconnect_transactions, :disconnect_all_transactions]
  end

  code_interface do
    define :by_id, args: [:id], action: :by_id
    define :get, args: [:id], action: :by_id
    define :read, action: :read
    define :list, action: :list
    define :read_global, action: :read_global
    define :read_missing_description, action: :read_missing_description
    define :by_checksum, args: [:blob_checksum]
    define :create, action: :create
    define :create_from_ksef, action: :create_from_ksef
    define :toggle_skip, action: :toggle_skip
    define :update_internal_note, args: [:internal_note], action: :update_internal_note
    define :update_tax_forecast_vat, action: :update_tax_forecast_vat
    define :update_blob_id, args: [:blob_id], action: :update_blob_id
    define :refresh_seller_display_name, action: :refresh_seller_display_name
    define :refresh_description, action: :refresh_description
    define :match_transactions, args: [:signal]
    define :match_pending_invoices, args: [:signal]
  end

  actions do
    defaults [:read]

    read :list do
      description "List cost invoices with search and reconciliation filters."

      pagination do
        required? false
        keyset? true
        max_page_size 100
      end

      argument :date_from, :date, description: "Inclusive start of the date_field range (YYYY-MM-DD)."

      argument :date_to, :date, description: "Inclusive end of the date_field range (YYYY-MM-DD)."

      argument :query, :string,
        constraints: [max_length: 500],
        description: "Full-text search over seller, description and invoice identifier."

      argument :currency, :string,
        description: "ISO currency code, e.g. PLN. Never add up amounts in different currencies."

      argument :amount_from, :decimal,
        description: "Minimum gross amount, inclusive, compared as an absolute value although costs are stored negative."

      argument :amount_to, :decimal,
        description: "Maximum gross amount, inclusive, compared as an absolute value although costs are stored negative."

      argument :merge_corrections, :boolean,
        default: false,
        description:
          "Hide corrections linked to an original and compare amounts after corrections. Use for totals and rankings."

      argument :date_field, :atom do
        constraints one_of: [:issue_date, :sale_date, :due_date, :any]
        default :issue_date

        description "Date compared with date_from and date_to; any matches either issue_date or sale_date."
      end

      argument :reconciliation, :atom do
        constraints one_of: [:pending, :matched, :skipped]

        description "Payment matching with bank transactions: pending has no matched payment yet, " <>
                      "matched is linked to a transaction, skipped is excluded from matching. " <>
                      "Linked corrections use the original invoice's reconciliation and are never listed separately."
      end

      argument :ids, {:array, :uuid_v7}, description: "Return only invoices with these IDs."

      argument :inserted_from, :utc_datetime,
        description: "Inclusive lower bound of when the invoice was recorded in Firmowid, not its document date."

      argument :inserted_to, :utc_datetime,
        description: "Exclusive upper bound of when the invoice was recorded in Firmowid, not its document date."

      argument :is_ksef_imported, :boolean, description: "Whether the invoice was imported from KSeF."

      argument :limit, :integer do
        constraints min: 1
        description "Page size, at most 100."
      end

      argument :listing_sort, :atom,
        constraints: [one_of: [:newest, :oldest]],
        description: "Order by issue date, newest or oldest first."

      validate compare(:date_to, greater_than_or_equal_to: :date_from),
        where: [present(:date_from), present(:date_to)],
        message: "Must be on or after date_from"

      prepare fn query, _context ->
        case Ash.Query.get_argument(query, :currency) do
          nil -> query
          currency -> Ash.Query.set_argument(query, :currency, String.upcase(currency))
        end
      end

      validate one_of(:currency, Enum.map(Money.known_currencies(), &to_string/1)),
        message: "Must be a recognized currency code"

      argument :source, :atom do
        constraints one_of: [:manual_import, :ksef]

        description "ksef for invoices imported from KSeF, manual_import for those added another way."
      end

      argument :in_digest, :atom do
        constraints one_of: [:yes, :no]

        description "Whether the invoice was already included in a KSeF cost invoice notification digest."
      end

      # Date filtering — conditional on date_field
      prepare {Firmowid.Ash.Invoicing.Preparations.FilterByDateField, []}
      prepare {Firmowid.Ash.Invoicing.Preparations.FilterBySourceAndDigestState, []}

      prepare {Firmowid.Ash.Preparations.ParadeDBSearch,
               columns: ~w(seller seller_display_name description invoice_identifier)a}

      prepare build(filter: expr(amount[:currency] == ^arg(:currency))) do
        where present(:currency)
      end

      prepare {Firmowid.Ash.Preparations.FilterByAmount, []}

      # Linked corrections affect the original's amount and have no separate reconciliation state.
      prepare build(filter: expr(is_nil(original_invoice_ksef_number) or is_nil(original_invoice.id))) do
        where any([argument_equals(:merge_corrections, true), present(:reconciliation)])
      end

      # :pending — no linked transactions, not skipped
      prepare build(
                filter:
                  expr(
                    not exists(transactions, true) and
                      skip_invoicing == false
                  )
              ) do
        where argument_equals(:reconciliation, :pending)
      end

      # :matched — linked to at least one transaction
      prepare build(filter: expr(exists(transactions, true))) do
        where argument_equals(:reconciliation, :matched)
      end

      # :skipped — no linked transactions, skipped
      prepare build(
                filter:
                  expr(
                    not exists(transactions, true) and
                      skip_invoicing == true
                  )
              ) do
        where argument_equals(:reconciliation, :skipped)
      end

      # Filter by IDs
      prepare build(filter: expr(id in ^arg(:ids))) do
        where present(:ids)
      end

      prepare build(filter: expr(inserted_at >= ^arg(:inserted_from))) do
        where present(:inserted_from)
      end

      prepare build(filter: expr(inserted_at < ^arg(:inserted_to))) do
        where present(:inserted_to)
      end

      prepare build(filter: expr(is_ksef_imported == ^arg(:is_ksef_imported))) do
        where present(:is_ksef_imported)
      end

      prepare build(sort: [issue_date: :desc]) do
        where absent(:query)
      end

      prepare build(limit: arg(:limit)) do
        where present(:limit)
      end

      prepare Firmowid.Ash.Invoicing.Preparations.SortInvoiceListing
    end

    read :by_id do
      description "Fetch a cost invoice by ID."
      get_by [:id]
    end

    read :by_checksum do
      description "Find a cost invoice by its blob's SHA-256 checksum."
      get? true

      argument :blob_checksum, :string, allow_nil?: false

      filter expr(exists(blob, blob_checksum == ^arg(:blob_checksum)))
    end

    read :read_global do
      description "Unscoped read for AshOban schedulers — reads across all organizations."
      multitenancy :allow_global
      pagination keyset?: true
    end

    read :read_missing_description do
      description "Scoped scheduler read for cost invoices missing generated descriptions."

      pagination do
        required? false
        keyset? true
      end
    end

    # -- Write actions --------------------------------------------------------

    create :create do
      description "Create a cost invoice from metadata extracted from an uploaded or e-mailed document."
      primary? true

      # KSeF identifiers come only from KSeF imports (:create_from_ksef). A number read
      # from a document is unverified and must not mark the invoice as KSeF-sourced.
      accept [
        :blob_id,
        :inbound_email_id,
        :seller,
        :seller_address,
        :seller_display_name,
        :account_number,
        :sale_date,
        :issue_date,
        :due_date,
        :items_list,
        :amount,
        :deductible_vat_amount,
        :invoice_identifier,
        :skip_invoicing,
        :seller_nip,
        :seller_country_code,
        :seller_email,
        :seller_phone,
        :invoice_type,
        :original_invoice_ksef_number,
        :payment_method,
        :internal_note
      ]

      validate present([
                 :seller,
                 :sale_date,
                 :issue_date,
                 :items_list,
                 :amount,
                 :invoice_identifier
               ])

      change ComputeCostInvoiceSellerDisplayName

      change ComputeCostInvoiceDescription

      change EnqueueMissingCostInvoiceDescriptionRefresh

      change fn changeset, _context ->
        validate_non_correction_amount_sign(changeset)
      end

      emit Signals, :cost_invoice_created, fields: [cost_invoice_id: :id]

      validate string_length(:internal_note, max: 10_000) do
        where present(:internal_note)
      end
    end

    create :create_from_ksef do
      description "Create a cost invoice from a KSeF import, generating names and descriptions in the background."

      accept [
        :blob_id,
        :inbound_email_id,
        :seller,
        :seller_address,
        :seller_display_name,
        :account_number,
        :sale_date,
        :issue_date,
        :due_date,
        :items_list,
        :amount,
        :deductible_vat_amount,
        :invoice_identifier,
        :skip_invoicing,
        :ksef_number,
        :ksef_permanent_storage_date,
        :ksef_downloaded_at,
        :seller_nip,
        :seller_country_code,
        :seller_email,
        :seller_phone,
        :invoice_type,
        :original_invoice_ksef_number,
        :payment_method,
        :internal_note
      ]

      validate present([
                 :seller,
                 :sale_date,
                 :issue_date,
                 :items_list,
                 :amount,
                 :invoice_identifier
               ])

      # A first KSeF import can hold thousands of invoices; generating names synchronously
      # would keep the fetch job running past its timeout.
      # The seller display name refresh also writes the description.
      change EnqueueMissingCostInvoiceSellerDisplayNameRefresh

      change fn changeset, _context ->
        validate_non_correction_amount_sign(changeset)
      end

      emit Signals, :cost_invoice_created, fields: [cost_invoice_id: :id]

      validate string_length(:internal_note, max: 10_000) do
        where present(:internal_note)
      end
    end

    update :toggle_skip do
      description "Toggle whether this cost invoice is skipped during invoicing workflows."
      require_atomic? false
      change filter(expr(not exists(original_invoice, true)))

      change fn changeset, _context ->
        current = Ash.Changeset.get_attribute(changeset, :skip_invoicing)
        Ash.Changeset.force_change_attribute(changeset, :skip_invoicing, !current)
      end
    end

    update :update_blob_id do
      description "Attach or replace the source blob for this cost invoice."
      accept [:blob_id]
      require_atomic? false
    end

    update :update_tax_forecast_vat do
      description "Record explicitly qualified deductible VAT for planning; nil means unknown, not zero."
      accept [:deductible_vat_amount]
    end

    update :update_internal_note do
      description "Update the internal note stored on this cost invoice."
      primary? true
      accept [:internal_note]
      require_atomic? false

      validate string_length(:internal_note, max: 10_000) do
        where present(:internal_note)
      end
    end

    update :refresh_description do
      description "Recompute the generated description for this cost invoice."
      require_atomic? false

      change ComputeCostInvoiceDescription
    end

    update :refresh_seller_display_name do
      description "Recompute the seller display name and description for this cost invoice."
      require_atomic? false

      change ComputeCostInvoiceSellerDisplayName

      # The description uses the seller activity found together with the display name.
      change ComputeCostInvoiceDescription
    end

    update :connect_transactions do
      description "Connect transactions to this cost invoice via the join table."
      require_atomic? false
      change RecordManualMatch
      argument :transaction_ids, {:array, :uuid}, allow_nil?: false

      change RequireTransactionIds
      change Firmowid.Ash.Invoicing.Changes.ValidateTransactionAvailability
      change manage_relationship(:transaction_ids, :transactions, type: :append)
    end

    update :disconnect_transactions do
      description "Disconnect the provided transactions from this cost invoice."
      require_atomic? false
      change RecordManualMatch
      argument :transaction_ids, {:array, :uuid}, allow_nil?: false

      change RequireTransactionIds
      change manage_relationship(:transaction_ids, :transactions, type: :remove)
    end

    update :disconnect_all_transactions do
      description "Disconnect all transactions from this cost invoice."
      require_atomic? false
      change {RecordManualMatch, current_transactions?: true}

      change fn changeset, _context ->
        Ash.Changeset.manage_relationship(changeset, :transactions, [], on_missing: :unrelate)
      end
    end

    action :transaction_suggestions,
           {:array, Firmowid.Ash.Invoicing.Types.TransactionSuggestion} do
      description "List transactions connected to this invoice and score pending ones against it, best match first."

      argument :invoice_id, :uuid,
        allow_nil?: false,
        description: "ID of an original invoice, not a correction."

      run {Firmowid.Ash.Invoicing.Actions.TransactionSuggestions, load: [:effective_amount, :transactions]}
    end

    action :match_transactions do
      description "Matches a newly created cost invoice to pending bank transactions."
      argument :signal, Signals.CostInvoiceCreated, allow_nil?: false

      run fn %{arguments: %{signal: signal}}, _context ->
        InvoiceMatching.match_cost_invoice(
          signal.cost_invoice_id,
          InvoiceMatching.matcher_scope(signal.organization_id)
        )
      end
    end

    action :match_pending_invoices do
      description "Matches pending cost invoices after a bank account sync."
      argument :signal, Finances.Signals.BankAccountSynced, allow_nil?: false

      run fn %{arguments: %{signal: signal}}, _context ->
        signal.organization_id
        |> InvoiceMatching.matcher_scope()
        |> InvoiceMatching.match_cost_invoices()
      end
    end
  end

  policies do
    bypass [{SystemActorRole, roles: [:avatar_cleanup]}, action(:read)] do
      authorize_if expr(blob_id == ^actor(:blob_id))
    end

    bypass {ActorRole, role: :admin} do
      authorize_if always()
    end

    policy action(:match_transactions) do
      authorize_if signal_in(Signals, :cost_invoice_created)
    end

    policy action(:match_pending_invoices) do
      authorize_if signal_in(Finances.Signals, :bank_account_synced)
    end

    bypass AshObanInteraction do
      authorize_if always()
    end

    bypass {SystemActorRole, roles: [:cost_invoice_processor]} do
      authorize_if always()
    end

    bypass {SystemActorRole,
            roles: [
              :ksef_session,
              :invoice_matcher,
              :analysis_reader,
              :ksef_digest,
              :billing_snapshotter
            ]} do
      authorize_if action_type(:read)
    end

    bypass {SystemActorRole, roles: [:invoice_matcher]} do
      authorize_if action([
                     :connect_transactions,
                     :disconnect_transactions,
                     :disconnect_all_transactions
                   ])
    end

    policy [action(:transaction_suggestions), {AtLeastRole, role: :invoicing}] do
      authorize_if always()
    end

    # Other system actors: no access
    policy IsSystemActor do
      forbid_if always()
    end

    # :invoicing and :accountant: read-only
    policy [action_type(:read), {AtLeastRole, role: :invoicing}] do
      authorize_if always()
    end

    # :accountant: write actions
    policy [
      action_type([:create, :update]),
      {AtLeastRole, role: :accountant}
    ] do
      authorize_if always()
    end

    policy [action_type(:action), {AtLeastRole, role: :accountant}] do
      authorize_if always()
    end
  end

  pub_sub do
    module FirmowidWeb.Core.Endpoint
    prefix "cost_invoice"

    publish :create, ["created", :_tenant]
    publish :toggle_skip, ["updated", :_tenant]
    publish :update_blob_id, ["updated", :_tenant]
    publish :update_internal_note, ["updated", :_tenant]
    publish :refresh_seller_display_name, ["updated", :_tenant]
    publish :refresh_description, ["updated", :_tenant]
    publish :connect_transactions, ["updated", :_tenant]
    publish :disconnect_transactions, ["updated", :_tenant]
    publish :disconnect_all_transactions, ["updated", :_tenant]
  end

  multitenancy do
    strategy :attribute
    attribute :organization_id
  end

  attributes do
    uuid_v7_primary_key :id

    attribute :seller, :string, public?: true
    attribute :seller_address, :string, public?: true
    attribute :seller_display_name, :string, public?: true
    attribute :account_number, :string, public?: true

    attribute :sale_date, :date, public?: true
    attribute :issue_date, :date, public?: true
    attribute :due_date, :date, public?: true

    attribute :amount, MoneyType, public?: true, allow_nil?: false

    attribute :deductible_vat_amount, MoneyType do
      public? true

      description "Explicitly qualified input VAT for planning, in PLN or the document currency. Positive deductions on ordinary invoices; signed VAT delta on corrections. Nil means unknown. Never inferred from gross/payment amount or a default rate."
    end

    attribute :description, :string,
      public?: true,
      allow_nil?: false,
      default: "",
      constraints: [allow_empty?: true]

    attribute :invoice_identifier, :string, public?: true
    attribute :internal_note, :string, public?: true

    attribute :items_list, {:array, :map}, public?: true, allow_nil?: false, default: []

    attribute :skip_invoicing, :boolean, default: false, public?: true

    attribute :ksef_number, :string, public?: true
    attribute :ksef_permanent_storage_date, :naive_datetime, public?: true
    attribute :ksef_downloaded_at, :utc_datetime_usec, public?: true

    attribute :seller_nip, :string, public?: true
    attribute :seller_country_code, :string, public?: true
    attribute :seller_email, :string, public?: true
    attribute :seller_phone, :string, public?: true

    attribute :invoice_type, :atom,
      public?: true,
      constraints: [one_of: ~w(vat kor zal roz upr kor_zal kor_roz)a]

    attribute :original_invoice_ksef_number, :string, public?: true

    attribute :payment_method, :atom,
      public?: true,
      constraints: [one_of: ~w(cash card voucher check loan bank_transfer mobile)a]

    attribute :blob_id, :uuid, public?: true
    attribute :inbound_email_id, :uuid, public?: true

    Resource.firmowid_timestamps()
  end

  relationships do
    belongs_to :organization, Firmowid.Ash.Core.Organization do
      allow_nil? false
    end

    belongs_to :blob, Firmowid.Ash.Blobs.Blob do
      allow_nil? true
      attribute_writable? true
      define_attribute? false
      source_attribute :blob_id
    end

    belongs_to :inbound_email, Firmowid.Ash.Invoicing.InboundEmail do
      allow_nil? true
      attribute_writable? true
      define_attribute? false
      source_attribute :inbound_email_id
    end

    many_to_many :transactions, Firmowid.Ash.Finances.Transaction do
      through CostInvoiceTransaction
      source_attribute_on_join_resource :cost_invoice_id
      destination_attribute_on_join_resource :transaction_id
    end

    # Named :correction_invoices (not :corrections as in SalesInvoice) because
    # cost invoice corrections link via ksef_number, not a direct FK.
    has_many :correction_invoices, __MODULE__ do
      source_attribute :ksef_number
      destination_attribute :original_invoice_ksef_number
      sort ksef_permanent_storage_date: :asc
    end

    has_one :latest_correction_invoice, __MODULE__ do
      source_attribute :ksef_number
      destination_attribute :original_invoice_ksef_number
      sort ksef_permanent_storage_date: :desc
    end

    belongs_to :original_invoice, __MODULE__ do
      allow_nil? true
      attribute_writable? true
      define_attribute? false
      source_attribute :original_invoice_ksef_number
      destination_attribute :ksef_number
    end

    has_many :entity_tags, Firmowid.Ash.Analysis.EntityTag do
      relationship_context %{data_layer: %{table: "cost_invoice_entity_tags"}}
      source_attribute :id
      destination_attribute :resource_id
    end

    has_one :ksef_invoice_digest_item, Firmowid.Ash.Invoicing.KsefInvoiceDigestItem do
      source_attribute :id
      destination_attribute :cost_invoice_id
    end
  end

  signals_in do
    from Signals do
      on :cost_invoice_created, :match_transactions, delivery: {AshOban.Signals, queue: :invoicing}
    end

    from Finances.Signals do
      on :bank_account_synced, :match_pending_invoices,
        delivery:
          {AshOban.Signals,
           queue: :invoicing, unique: [keys: [:organization_id], states: [:available, :scheduled, :retryable]]}
    end
  end

  calculations do
    calculate :is_ksef_imported,
              :boolean,
              expr(
                not (is_nil(ksef_downloaded_at) and is_nil(ksef_permanent_storage_date) and
                       is_nil(ksef_number))
              )

    calculate :invoice_source,
              :string,
              expr(
                if is_ksef_imported do
                  "ksef"
                else
                  "document"
                end
              )

    calculate :is_in_ksef_digest,
              :boolean,
              expr(exists(ksef_invoice_digest_item, true))

    calculate :is_deletable,
              :boolean,
              expr(not is_ksef_imported)

    calculate :amount_value, :decimal, expr(amount[:amount])

    calculate :amount_currency, :string, expr(amount[:currency])

    # Effective fields — coalesce latest correction snapshot with original.
    # DB-pushable, filterable, sortable.
    calculate :has_corrections, :boolean, expr(not is_nil(corrections_amount))

    calculate :effective_amount,
              MoneyType,
              expr(
                if is_nil(corrections_amount) or latest_correction_currency != amount_currency do
                  amount
                else
                  composite_type(
                    %{currency: amount_currency, amount: amount_value + corrections_amount},
                    MoneyType
                  )
                end
              )

    calculate :effective_sale_date, :date, expr(latest_correction_sale_date || sale_date)

    calculate :effective_due_date, :date, expr(latest_correction_due_date || due_date)

    calculate :effective_seller, :string, expr(latest_correction_seller || seller)

    calculate :effective_seller_address,
              :string,
              expr(latest_correction_seller_address || seller_address)

    calculate :effective_seller_display_name,
              :string,
              expr(latest_correction_seller_display_name || seller_display_name)

    calculate :effective_seller_nip, :string, expr(latest_correction_seller_nip || seller_nip)

    calculate :effective_seller_country_code,
              :string,
              expr(latest_correction_seller_country_code || seller_country_code)

    calculate :effective_seller_email,
              :string,
              expr(latest_correction_seller_email || seller_email)

    calculate :effective_seller_phone,
              :string,
              expr(latest_correction_seller_phone || seller_phone)

    calculate :effective_payment_method,
              :atom,
              expr(latest_correction_payment_method || payment_method)

    calculate :effective_account_number,
              :string,
              expr(latest_correction_account_number || account_number)
  end

  aggregates do
    sum :corrections_amount, :correction_invoices, :amount_value do
      filter expr(amount_currency == parent(amount_currency))
    end

    first :latest_correction_currency, :correction_invoices, :amount_currency do
      sort ksef_permanent_storage_date: :desc
    end

    first :latest_correction_sale_date, :correction_invoices, :sale_date do
      sort ksef_permanent_storage_date: :desc
    end

    first :latest_correction_due_date, :correction_invoices, :due_date do
      sort ksef_permanent_storage_date: :desc
    end

    first :latest_correction_seller, :correction_invoices, :seller do
      sort ksef_permanent_storage_date: :desc
    end

    first :latest_correction_seller_address, :correction_invoices, :seller_address do
      sort ksef_permanent_storage_date: :desc
    end

    first :latest_correction_seller_display_name, :correction_invoices, :seller_display_name do
      sort ksef_permanent_storage_date: :desc
    end

    first :latest_correction_seller_nip, :correction_invoices, :seller_nip do
      sort ksef_permanent_storage_date: :desc
    end

    first :latest_correction_seller_country_code, :correction_invoices, :seller_country_code do
      sort ksef_permanent_storage_date: :desc
    end

    first :latest_correction_seller_email, :correction_invoices, :seller_email do

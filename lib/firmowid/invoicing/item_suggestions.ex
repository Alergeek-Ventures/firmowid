defmodule Firmowid.Invoicing.ItemSuggestions do
  @moduledoc """
  Names the organization's sales invoice items are likely to have, suggested in
  the item name field.

  One list per organization, generated by a model from the item names the
  organization has used and from its registered activity (PKD), and regenerated
  monthly by `Firmowid.Invoicing.Workers.ItemSuggestionsWorker`. Its length
  depends on the business: a few names for a narrow service, dozens for a shop.
  """
  use Ash.Resource,
    otp_app: :firmowid,
    domain: Firmowid.Invoicing,
    data_layer: AshPostgres.DataLayer,
    authorizers: [Ash.Policy.Authorizer]

  alias Firmowid.Checks.AtLeastRole
  alias Firmowid.Checks.SystemActorRole
  alias Firmowid.Resource

  require Resource

  postgres do
    table "item_suggestions"
    repo Firmowid.Repo

    references do
      reference :organization, on_delete: :delete
    end
  end

  actions do
    read :current do
      description "Reads the organization's item name suggestions, nil before the first generation."
      get? true
    end

    create :generate do
      description "Generates the organization's item name suggestions, replacing the earlier ones."
      upsert? true
      upsert_identity :unique_organization
      upsert_fields {:replace_all_except, [:id, :inserted_at]}
      change Firmowid.Invoicing.Changes.GenerateItemSuggestions
    end
  end

  policies do
    policy {SystemActorRole, roles: [:item_suggester]} do
      authorize_if action([:current, :generate])
    end

    policy {AtLeastRole, role: :invoicing} do
      authorize_if action(:current)
    end
  end

  multitenancy do
    strategy :attribute
    attribute :organization_id
  end

  attributes do
    uuid_v7_primary_key :id

    attribute :suggestions, {:array, Firmowid.Invoicing.ItemSuggestions.Suggestion},
      allow_nil?: false,
      default: [],
      public?: true,
      description: "Most likely first."

    Resource.firmowid_timestamps()
  end

  relationships do
    belongs_to :organization, Firmowid.Core.Organization do
      allow_nil? false
    end
  end

  identities do
    identity :unique_organization, [:organization_id]
  end
end

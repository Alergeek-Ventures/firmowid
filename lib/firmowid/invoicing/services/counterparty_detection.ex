defmodule Firmowid.Invoicing.Services.CounterpartyDetection do
  @moduledoc """
  Finds buyers of issued sales invoices that have no counterparty yet and
  proposes, for each of them, either an existing counterparty to link or a new
  one prefilled from the invoices and the VAT white list.

  Buyers are grouped by PESEL, by tax ID (with country and type) or, without
  either, by a name stripped of legal forms. An existing counterparty matches
  by the same identifier, or by the same stripped name when neither side has a
  conflicting identifier.
  """

  alias Firmowid.Core.Nip
  alias Firmowid.Core.Services.VatApiClient
  alias Firmowid.Invoicing
  alias Firmowid.Invoicing.Counterparty
  alias Firmowid.Invoicing.CountryCodes
  alias Firmowid.Invoicing.IdentifierNormalization
  alias Firmowid.Invoicing.SalesInvoice
  alias Firmowid.Invoicing.Services.CounterpartyProposalCleanup
  alias Firmowid.Scope

  require Ash.Query

  @type registry :: %{name: String.t(), address: String.t() | nil, vat_status: String.t() | nil}
  @type group :: %{
          optional(:overrides) => map(),
          key: String.t(),
          buyer: map(),
          invoice_ids: [String.t()],
          invoice_numbers: [String.t()],
          last_issue_date: Date.t() | nil,
          totals: [Money.t()],
          match: %{counterparty: Counterparty.t(), reason: :identifier | :name} | nil,
          registry: registry() | nil,
          cleaned: CounterpartyProposalCleanup.result() | nil
        }

  @buyer_fields ~w(type tax_id pesel full_name given_name surname display_name address country
                   is_different_mail_address mail_address mail_country email phone)a

  # Longest forms first so "sp. z o.o." is not left as "sp." after removing "z o.o.".
  @legal_forms [
    "spółka z ograniczoną odpowiedzialnością",
    "spółka komandytowo-akcyjna",
    "spółka komandytowa",
    "spółka jawna",
    "spółka akcyjna",
    "sp. z o.o.",
    "sp. z o. o.",
    "sp.z o.o.",
    "sp. k.",
    "sp.k.",
    "sp. j.",
    "sp.j.",
    "s.a.",
    "inc.",
    "inc",
    "ltd.",
    "ltd",
    "llc",
    "gmbh",
    "s.r.o.",
    "b.v.",
    "ab"
  ]

  # Model calls one page load may start; the rest are generated on later loads,
  # buyers with the most invoices first.
  @generation_limit 25

  @doc "Groups the unlinked buyers of issued invoices, most invoices first."
  @spec list(Scope.t()) :: [group()]
  def list(%Scope{} = scope) do
    counterparties =
      Invoicing.list_counterparties!(%{status: :all}, load: [:display_label], scope: scope)

    %{submission: :confirmed}
    |> SalesInvoice.query_to_list(scope: scope)
    |> Ash.Query.filter(is_nil(counterparty_id))
    |> Ash.Query.sort(issue_date: :desc)
    |> Ash.Query.load(:amount)
    |> then(&SalesInvoice.list!(query: &1, scope: scope))
    |> Enum.group_by(&group_key/1)
    |> Enum.map(fn {key, invoices} -> build_group(key, invoices, counterparties) end)
    |> Enum.sort_by(&{-length(&1.invoice_ids), &1.buyer.label})
  end

  @doc """
  Looks up the Polish NIPs of the groups in the VAT
  white list, 30 per request. Returns the registry data by group key.
  """
  @spec registry_data([group()]) :: {:ok, %{String.t() => registry()}} | {:error, term()}
  def registry_data(groups) do
    nips = for group <- groups, nip = registry_nip(group), do: {nip, group.key}

    nips
    |> Enum.map(&elem(&1, 0))
    |> Enum.uniq()
    |> Enum.chunk_every(30)
    |> Enum.reduce_while({:ok, []}, fn batch, {:ok, found} ->
      case VatApiClient.fetch_by_nips(batch) do
        {:ok, subjects} -> {:cont, {:ok, subjects ++ found}}
        {:error, _reason} = error -> {:halt, error}
      end
    end)
    |> case do
      {:ok, subjects} ->
        by_nip = Map.new(subjects, &{&1["nip"], &1})

        {:ok,
         for {nip, key} <- nips, subject = by_nip[nip], into: %{} do
           {key,
            %{
              name: subject["name"],
              address: subject["workingAddress"] || subject["residenceAddress"],
              vat_status: subject["statusVat"]
            }}
         end}

      {:error, _reason} = error ->
        error
    end
  end

  @doc """
  Returns the cleaned-up proposal of each group by key. Stored proposals are
  reused while the invoice and register data they came from stay the same; the
  rest are generated by the model and stored, at most #{@generation_limit} per call.
  Groups not generated yet or whose cleanup failed are left out.
  """
  @spec cleaned_proposals([group()], %{String.t() => registry()}, Scope.t()) ::
          %{String.t() => CounterpartyProposalCleanup.result()}
  def cleaned_proposals(groups, registry, scope) do
    # A list in group order, so the generation limit keeps the buyers with the most invoices.
    inputs = Enum.map(groups, &{&1.key, cleanup_input(&1, registry[&1.key])})

    stored =
      inputs
      |> Enum.map(&elem(&1, 0))
      |> Invoicing.list_counterparty_proposals!(scope: scope)
      |> Map.new(&{&1.group_key, &1})

    {fresh, missing} =
      Enum.split_with(inputs, fn {key, input} ->
        hash = source_hash(input)
        match?(%{source_hash: ^hash}, stored[key])
      end)

    generated =
      missing
      |> Enum.take(@generation_limit)
      |> Task.async_stream(
        fn {key, input} ->
          with %{} = cleaned <- CounterpartyProposalCleanup.clean(input) do
            Invoicing.record_counterparty_proposal!(
              Map.merge(cleaned, %{group_key: key, source_hash: source_hash(input)}),
              scope: scope
            )

            {key, cleaned}
          end
        end,
        max_concurrency: 8,
        timeout: 90_000,
        on_timeout: :kill_task
      )
      |> Enum.flat_map(fn
        {:ok, {key, cleaned}} -> [{key, cleaned}]
        _failed -> []
      end)

    fresh
    |> Map.new(fn {key, _input} ->
      {key, Map.take(stored[key], [:display_name, :full_name, :given_name, :surname, :address])}
    end)
    |> Map.merge(Map.new(generated))
  end

  defp cleanup_input(group, registry) do
    %{
      type: group.buyer.type,
      full_name: group.buyer.full_name,
      given_name: group.buyer.given_name,
      surname: group.buyer.surname,
      tax_id: group.buyer.tax_id,
      country: group.buyer.country,
      address: group.buyer.address,
      registry_name: registry && registry.name,
      registry_address: registry && registry.address
    }
  end

  defp source_hash(input), do: input |> :erlang.phash2() |> Integer.to_string()

  @doc "The NIP to look up in the VAT white list: Polish companies with a valid NIP."
  @spec registry_nip(group()) :: String.t() | nil
  def registry_nip(%{buyer: %{type: :company, country: "PL", tax_id: tax_id}}) when is_binary(tax_id) do
    if Nip.valid?(tax_id), do: Nip.normalize_digits(tax_id)
  end

  def registry_nip(_group), do: nil

  @doc """
  The attributes of the counterparty proposed for a group: the latest invoice's
  buyer, completed with the VAT white list, with the legal form dropped from the display name.
  Fields the user corrected come in the group's optional `:overrides`.
  """
  @spec proposed_attributes(group()) :: map()
  def proposed_attributes(%{buyer: buyer, registry: registry} = group) do
    full_name = present(buyer.full_name) || (registry && registry.name)

    buyer
    |> Map.take(@buyer_fields)
    |> Map.merge(%{
      full_name: full_name,
      address: present(buyer.address) || (registry && registry.address),
      display_name: display_name(buyer, full_name)
    })
    |> Map.merge(cleaned_fields(group))
    |> Map.merge(Map.get(group, :overrides, %{}))
    |> without_eu_vat_prefix()
    |> Map.reject(fn {_field, value} -> value in [nil, ""] end)
  end

  # A counterparty keeps its country apart, so its EU VAT number is stored without
  # the prefix invoices often carry (SE123456789001 fails the 12-character rule).
  # Polish NIPs may keep PL, which the NIP validation accepts.
  defp without_eu_vat_prefix(%{tax_id: tax_id, country: country} = attributes)
       when is_binary(tax_id) and country != "PL" do
    if country in CountryCodes.eu_countries_with_aliases() do
      prefix = if country == "GR", do: "EL", else: country
      %{attributes | tax_id: String.replace(tax_id, ~r/^\s*#{prefix}[\s-]*/i, "")}
    else
      attributes
    end
  end

  defp without_eu_vat_prefix(attributes), do: attributes

  defp cleaned_fields(%{cleaned: nil}), do: %{}

  defp cleaned_fields(%{cleaned: cleaned}), do: Map.reject(cleaned, fn {_field, value} -> is_nil(value) end)

  # People are shown by their names, so only companies get a short display name.
  defp display_name(%{type: :company} = buyer, full_name), do: short_name(present(buyer.display_name) || full_name)

  defp display_name(buyer, _full_name), do: present(buyer.display_name)

  @doc "Links every invoice of the group to the counterparty, all or none."
  @spec link(group(), String.t(), Scope.t()) :: :ok | {:error, term()}
  def link(group, counterparty_id, scope) do
    case Ash.transact(SalesInvoice, fn -> link_invoices(group, counterparty_id, scope) end) do
      {:ok, :ok} -> :ok
      {:error, _error} = error -> error
    end
  end

  @doc "Creates the proposed counterparty and links the group's invoices to it, all or none."
  @spec create_and_link(group(), Scope.t()) :: {:ok, Counterparty.t()} | {:error, term()}
  def create_and_link(group, scope) do
    Ash.transact([Counterparty, SalesInvoice], fn ->
      with {:ok, counterparty} <-
             Invoicing.create_counterparty(proposed_attributes(group), scope: scope),
           :ok <- link_invoices(group, counterparty.id, scope) do
        counterparty
      end
    end)
  end

  defp link_invoices(group, counterparty_id, scope) do
    Enum.reduce_while(group.invoice_ids, :ok, fn invoice_id, :ok ->
      with {:ok, invoice} <- Invoicing.get_sales_invoice(invoice_id, scope: scope),
           {:ok, _invoice} <-
             Invoicing.link_sales_invoice_counterparty(invoice, counterparty_id, scope: scope) do
        {:cont, :ok}
      else
        {:error, _error} = error -> {:halt, error}
      end
    end)
  end

  @doc "Removes legal forms and punctuation, for comparing names."
  @spec normalize_name(String.t() | nil) :: String.t() | nil
  def normalize_name(nil), do: nil

  def normalize_name(name) do
    name
    |> String.downcase()
    |> strip_legal_forms()
    |> String.replace(~r/[^\p{L}\p{N}]+/u, " ")
    |> String.trim()
    |> present()
  end

  defp group_key(invoice) do
    cond do
      pesel = IdentifierNormalization.normalize_pesel(invoice.buyer_pesel) ->
        "pesel:#{pesel}"

      tax_id = identifier(%{pesel: nil, tax_id: invoice.buyer_id, country: invoice.buyer_country}) ->
        "tax:#{invoice.buyer_country}:#{invoice.buyer_type}:#{tax_id}"

      true ->
        "name:#{invoice.buyer_country}:#{invoice.buyer_type}:#{normalize_name(buyer_label(invoice))}"
    end
  end

  defp build_group(key, [latest | _] = invoices, counterparties) do
    buyer =
      latest
      |> buyer()
      |> Map.put(:label, buyer_label(latest))

    %{
      key: key,
      buyer: buyer,
      invoice_ids: Enum.map(invoices, & &1.id),
      invoice_numbers: Enum.map(invoices, & &1.invoice_number),
      last_issue_date: latest.issue_date,
      totals: totals(invoices),
      match: match(buyer, counterparties),
      registry: nil,
      cleaned: nil
    }
  end

  defp buyer(invoice) do
    %{
      type: invoice.buyer_type,
      # Placeholders like "-" mean the invoice had no identifier.
      tax_id: if(invoice.buyer_id && invoice.buyer_id =~ ~r/[[:alnum:]]/u, do: invoice.buyer_id),
      pesel: invoice.buyer_pesel,
      full_name: invoice.buyer_full_name,
      given_name: invoice.buyer_given_name,
      surname: invoice.buyer_surname,
      display_name: invoice.buyer_display_name,
      address: invoice.buyer_address,
      country: invoice.buyer_country,
      is_different_mail_address: invoice.buyer_is_different_mail_address,
      mail_address: invoice.buyer_mail_address,
      mail_country: invoice.buyer_mail_country,
      email: invoice.buyer_email,
      phone: invoice.buyer_phone
    }
  end

  defp buyer_label(invoice) do
    present(invoice.buyer_display_name) || present(invoice.buyer_full_name) ||
      String.trim("#{invoice.buyer_given_name} #{invoice.buyer_surname}")
  end

  defp totals(invoices) do
    invoices
    |> Enum.map(& &1.amount)
    |> Enum.reject(&is_nil/1)
    |> Enum.group_by(& &1.currency)
    |> Enum.map(fn {_currency, amounts} -> Enum.reduce(amounts, &Money.add!/2) end)
  end

  defp match(buyer, counterparties) do
    candidates =
      Enum.filter(counterparties, &(&1.type == buyer.type and &1.country == buyer.country))

    cond do
      counterparty = Enum.find(candidates, &same_identifier?(&1, buyer)) ->
        %{counterparty: counterparty, reason: :identifier}

      counterparty = Enum.find(candidates, &same_name?(&1, buyer)) ->
        %{counterparty: counterparty, reason: :name}

      true ->
        nil
    end
  end

  defp same_identifier?(counterparty, buyer) do
    case identifier(buyer) do
      nil -> false
      identifier -> identifier == identifier(counterparty)
    end
  end

  # A shared name links only when the identifiers do not contradict it.
  defp same_name?(counterparty, buyer) do
    name = normalize_name(buyer.label)

    conflicting? =
      case {identifier(buyer), identifier(counterparty)} do
        {nil, _identifier} -> false
        {_identifier, nil} -> false
        {own, other} -> own != other
      end

    not is_nil(name) and not conflicting? and
      name in [normalize_name(counterparty.full_name), normalize_name(counterparty.display_label)]
  end

  defp identifier(%{pesel: pesel, tax_id: tax_id, country: country}) do
    case IdentifierNormalization.normalize_pesel(pesel) do
      nil ->
        tax_id |> IdentifierNormalization.normalize_tax_id() |> without_country_prefix(country)

      pesel ->
        {:pesel, pesel}
    end
  end

  # EU VAT numbers are written with or without the country prefix (BE0123456789
  # and 0123456789); Greece uses EL.
  defp without_country_prefix(nil, _country), do: nil

  defp without_country_prefix(tax_id, country) do
    prefix = if country == "GR", do: "EL", else: country

    case tax_id do
      ^prefix <> rest when rest != "" -> rest
      tax_id -> tax_id
    end
  end

  defp short_name(nil), do: nil

  # Drops legal forms only from the end ("ACME LOGISTYKA SPÓŁKA Z O.O. SPÓŁKA KOMANDYTOWA"),
  # so "Example Corp, Inc d/b/a Brand" keeps its middle.
  defp short_name(full_name) do
    stripped =
      Enum.reduce(@legal_forms, full_name, fn form, acc ->
        String.replace(acc, ~r/[\s,]+#{Regex.escape(form)}[\s,.]*$/iu, "")
      end)

    case stripped do
      ^full_name -> full_name |> String.replace(~r/[\s,]+$/u, "") |> capitalize() |> present()
      shorter -> short_name(shorter)
    end
  end

  # Names written in capitals ("ACME", "ACME LOGISTYKA") read as "Acme" and
  # "Acme Logistyka"; words of up to three letters stay as acronyms ("10 ABC").
  defp capitalize(name) do
    if name == String.upcase(name) do
      name
      |> String.split(" ")
      |> Enum.map_join(" ", fn word ->
        if String.length(word) <= 3, do: word, else: String.capitalize(word)
      end)
    else
      name
    end
  end

  defp strip_legal_forms(name) do
    @legal_forms
    |> Enum.reduce(name, fn form, acc ->
      String.replace(acc, ~r/(^|[\s,])#{Regex.escape(form)}(?=$|[\s,])/iu, " ")
    end)
    |> String.replace(~r/\s+/u, " ")
  end

  defp present(nil), do: nil

  defp present(value) do
    case String.trim(value) do
      "" -> nil
      trimmed -> trimmed
    end
  end
end
